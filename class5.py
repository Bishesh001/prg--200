# converting nepali rupesss in to usd
# USD to NPR Converter (simple version, no functions)

rate = 152.50  # 1 USD = 152.50 NPR (approx.)

usd1 = 5
usd2 = 50
usd3 = 500
usd4 = 5000

npr1 = usd1 * rate
npr2 = usd2 * rate
